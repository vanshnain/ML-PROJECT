tuning_results = []

# Try different parameter combinations
for depth in param_grid["model__max_depth"]:
    for split in param_grid["model__min_samples_split"]:
        for leaf in param_grid["model__min_samples_leaf"]:

            fold_rmse = []

            for val_year in validation_years:

                train_mask = train_df["Crop_Year"] < val_year
                val_mask = train_df["Crop_Year"] == val_year

                X_tr = train_df.loc[train_mask, feature_cols]
                X_val = train_df.loc[val_mask, feature_cols]

                y_tr = np.log1p(
                    train_df.loc[train_mask, "Yield"].values
                )

                y_val = train_df.loc[val_mask, "Yield"].values

                if len(X_tr) == 0 or len(X_val) == 0:
                    continue

                estimator = clone(models["Decision Tree"])

                estimator.set_params(
                    model__max_depth=depth,
                    model__min_samples_split=split,
                    model__min_samples_leaf=leaf
                )

                estimator.fit(X_tr, y_tr)

                pred = np.maximum(
                    0,
                    np.expm1(estimator.predict(X_val))
                )

                rmse = np.sqrt(mean_squared_error(y_val, pred))
                fold_rmse.append(rmse)

            if fold_rmse:
                tuning_results.append({
                    "max_depth": depth,
                    "min_samples_split": split,
                    "min_samples_leaf": leaf,
                    "Average_RMSE": np.mean(fold_rmse)
                })

